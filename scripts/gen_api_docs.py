"""Regenerate the route table in docs/API.md from the live FastAPI app.

Run from backend/:   python ../scripts/gen_api_docs.py          (rewrites docs/API.md between the markers)
                     python ../scripts/gen_api_docs.py --check  (exit 1 if docs/API.md is out of date; used in CI)

The required role is derived from each route's dependency tree (require_admin / require_operator /
require_any / get_current_user), so the table cannot drift from the code.
"""

from __future__ import annotations

import inspect
import logging
import sys
from pathlib import Path

from fastapi.routing import APIRoute

logging.disable(logging.CRITICAL)
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.main import app  # noqa: E402
from app.security import get_current_user, require_admin, require_any, require_operator  # noqa: E402

BEGIN, END = "<!-- BEGIN GENERATED ROUTES -->", "<!-- END GENERATED ROUTES -->"
ROLE_ORDER = [
    (require_admin, "admin"),
    (require_operator, "admin, inspector"),
    (require_any, "any signed-in"),
    (get_current_user, "any signed-in"),
]


def _calls(dependant) -> set:
    out = set()
    for d in dependant.dependencies:
        out.add(d.call)
        out |= _calls(d)
    return out


def _role(route: APIRoute) -> str:
    calls = _calls(route.dependant)
    for fn, label in ROLE_ORDER:
        if fn in calls:
            return label
    return "public"


def _summary(route: APIRoute) -> str:
    doc = inspect.getdoc(route.endpoint) or ""
    line = doc.strip().splitlines()[0] if doc.strip() else route.name.replace("_", " ")
    return line.replace("``", "`").replace("|", "\\|")


def _all_api_routes(routes) -> list[APIRoute]:
    """Collect APIRoute objects, descending into included routers and mounts without relying on their internals."""
    out: list[APIRoute] = []
    for r in routes:
        if isinstance(r, APIRoute):
            out.append(r)
        elif getattr(r, "original_router", None) is not None:  # FastAPI >= 0.13x included-router wrapper
            out += _all_api_routes(r.original_router.routes)
        elif getattr(r, "routes", None):
            out += _all_api_routes(r.routes)
    return out


def render() -> str:
    candidates = _all_api_routes(app.routes)
    groups: dict[str, list[str]] = {}
    missing = []
    for path, ops in app.openapi()["paths"].items():
        for method, op in ops.items():
            m = method.upper()
            matches = [
                r for r in candidates if m in r.methods and path.endswith(r.path) and op.get("operationId", "").startswith(r.name)
            ]
            if not matches:
                missing.append(f"{m} {path}")
                continue
            r = max(matches, key=lambda x: len(x.path))
            tag = (op.get("tags") or [path.split("/")[2]])[0]
            groups.setdefault(str(tag), []).append(f"| `{m}` | `{path}` | {_role(r)} | {_summary(r)} |")
    if missing:
        raise SystemExit(f"could not resolve endpoint for: {missing}")
    n = sum(len(v) for v in groups.values())
    lines = [BEGIN, "", f"_{n} operations, generated by `scripts/gen_api_docs.py`. Do not edit by hand._", ""]
    for tag in sorted(groups):
        lines += [f"### {tag}", "", "| Method | Path | Role | Description |", "|---|---|---|---|", *groups[tag], ""]
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    target = ROOT / "docs" / "API.md"
    text = target.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    new = text[:start] + render() + text[end:]
    if "--check" in sys.argv:
        if new != text:
            print("docs/API.md is out of date: run  python ../scripts/gen_api_docs.py  from backend/")
            return 1
        print("docs/API.md is up to date")
        return 0
    target.write_text(new, encoding="utf-8")
    print(f"updated {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
